def load_metrics():
    """Loads all experimental metrics JSON files."""
    prop_path = config.METRICS_DIR / "proposed_metrics.json"
    base_path = config.METRICS_DIR / "baseline_metrics.json"
    ablation_path = config.METRICS_DIR / "ablation_metrics.json"
    tuning_path = config.METRICS_DIR / "tuning_metrics.json"
    
    with open(prop_path, "r") as f:
        proposed = json.load(f)
    with open(base_path, "r") as f:
        baselines = json.load(f)
    with open(ablation_path, "r") as f:
        ablation = json.load(f)
    with open(tuning_path, "r") as f:
        tuning = json.load(f)
        
    return proposed, baselines, ablation, tuning

